async (page) => {
  const check = (value, name) => { if (!value) throw new Error(name); };
  const errors = [];
  const calls = [];
  const user = { id: 'recovery-test', email: 'test@example.com' };
  const session = { access_token: 'test-token', refresh_token: 'test-refresh', expires_in: 3600, user };
  let failRead = false;
  let empty = false;
  page.on('pageerror', error => errors.push(error.message));
  await page.unrouteAll({ behavior: 'wait' });
  await page.route('**/auth/v1/**', async route => {
    const req = route.request();
    calls.push({ url: req.url(), method: req.method(), body: req.postDataJSON() });
    await route.fulfill({ contentType: 'application/json', body: JSON.stringify(req.url().endsWith('/user') ? user : req.url().includes('/verify') ? session : {}) });
  });
  await page.route('**/rest/v1/**', async route => {
    const req = route.request();
    calls.push({ url: req.url(), method: req.method(), body: req.postDataJSON() });
    await route.fulfill({ status: failRead ? 503 : 200, contentType: 'application/json', body: JSON.stringify(failRead ? { message: 'Temporarily unavailable' } : empty ? [] : [{ tasks: [{ id: 'cloud-task', title: 'Cloud original', category: 'work', date: '2026-09-18' }], settings: {}, templates: [] }]) });
  });
  await page.goto('http://127.0.0.1:4194/index.html');
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await page.reload();
  await page.evaluate(() => {
    tasks = [{ id: 'guest-task', title: 'Guest original', category: 'work', date: '2026-09-18' }];
    persist();
  });
  check(await page.evaluate(() => getAuthRedirectUrl()) === 'https://dre645494896.github.io/-/', 'local requests use production redirect');
  await page.locator('#accountStatus').click();
  await page.locator('#authForgotBtn').click();
  await page.locator('#authEmail').fill('test@example.com');
  await page.locator('#authSubmitBtn').click();
  await page.waitForFunction(() => document.querySelector('#authStatusText').textContent.includes('你将收到'));
  check(calls.filter(c => c.url.includes('/recover')).every(c => c.url.includes('redirect_to=https%3A%2F%2Fdre645494896.github.io%2F-%2F')), 'recovery POST redirect');
  await page.goto('http://127.0.0.1:4194/index.html#access_token=test-token&refresh_token=test-refresh&type=recovery');
  await page.locator('#authPasswordConfirm').waitFor({ state: 'visible' });
  check(await page.evaluate(() => !location.hash), 'URL tokens removed');
  await page.reload();
  await page.locator('#authPasswordConfirm').waitFor({ state: 'visible' });
  check(await page.evaluate(() => getRecoveryState() !== null), 'recovery survives reload');
  await page.evaluate(async () => { queueCloudSave(); await saveCloudData(); await loadCloudData(); });
  check(!calls.some(c => c.url.includes('/rest/') && c.method === 'POST'), 'recovery never uploads guest data');
  await page.locator('#authPassword').fill('test-new-password');
  await page.locator('#authPasswordConfirm').fill('test-new-password');
  await page.locator('#authSubmitBtn').click();
  await page.locator('#authForm').waitFor({ state: 'hidden' });
  check(await page.evaluate(() => tasks[0].id === 'cloud-task'), 'reset hydrates original cloud data');
  check(await page.evaluate(() => sessionStorage.getItem(AUTH_RECOVERY_KEY) === null), 'recovery flag cleared after success');
  check(await page.evaluate(() => Object.keys(localStorage).some(k => k.startsWith('jijiandaiban_local_backup_guest_'))), 'guest data preserved in backup');
  check(!calls.some(c => c.url.includes('/rest/') && c.method === 'POST'), 'login read has no implicit cloud writes');
  failRead = true;
  await page.evaluate(() => loadCloudData());
  check(await page.evaluate(() => cloudWritableUserId === null), 'failed read blocks writes');
  await page.evaluate(async () => { persist(); await saveCloudData(); });
  check(!calls.some(c => c.url.includes('/rest/') && c.method === 'POST'), 'failed read never uploads');
  failRead = false;
  await page.evaluate(() => syncNow());
  check(await page.evaluate(() => cloudWritableUserId === currentUser.id), 'manual sync retries read');
  await page.evaluate(() => saveCloudData());
  check(calls.some(c => c.url.includes('/rest/') && c.method === 'POST' && c.body.tasks[0].id === 'cloud-task'), 'verified hydrated account can save');
  await page.evaluate(() => signOut());
  await page.reload();
  await page.locator('#accountStatus').click();
  await page.locator('#authOtpModeBtn').click();
  await page.locator('#authEmail').fill('test@example.com');
  await page.locator('#authOtp').fill('123456');
  empty = true;
  await page.locator('#authSubmitBtn').click();
  await page.locator('#authForm').waitFor({ state: 'hidden' });
  check(await page.evaluate(() => tasks.length === 0), 'empty account never adopts previous tasks');
  await page.goto('http://127.0.0.1:4194/index.html#error=access_denied&error_code=otp_expired&error_description=Email+link+is+invalid+or+has+expired');
  await page.locator('#authForm').waitFor({ state: 'visible' });
  await page.evaluate(() => updateCloudUi());
  check((await page.locator('#authStatusText').textContent()).includes('已过期'), 'callback errors persist');
  check(errors.length === 0, 'no page errors: ' + errors.join(', '));
  console.log('PASS: production redirect, recovery reload, token cleanup, write guards, cloud/guest preservation, failed read retry, OTP without send state, empty account, persistent errors. Mocked APIs only.');
}
